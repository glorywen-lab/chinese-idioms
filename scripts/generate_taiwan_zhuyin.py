def get_taiwan_zhuyin(idiom):
    # 1. Exact match in MOE dictionary
    if idiom in taiwan_moe_corrections:
        return taiwan_moe_corrections[idiom]
        
    # 2. Convert using pypinyin BOPOMOFO style
    raw = pinyin(idiom, style=Style.BOPOMOFO)
    syllables = [item[0] for item in raw]
    return " ".join(syllables)

